     "한국어 위키백과에서 근거 문서를 찾기 위한 검색어를 만든다.\n"
     "규칙:\n"
     "- 검색어는 최대 {max_queries}개, 각각 2~6단어의 명사구로 쓴다.\n"
     "- 질문에 답하는 데 필요한 개념(병원체, 전파 경로, 증상, 예방접종, 관련 제도 등)을 고른다.\n"
